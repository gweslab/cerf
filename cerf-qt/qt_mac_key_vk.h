struct MacKeySidedVk {
    uint32_t code;
    uint8_t  vk;
};

/* Events.h kVK_Shift 0x38, kVK_Option 0x3A, kVK_Control 0x3B, kVK_RightShift 0x3C,
   kVK_RightOption 0x3D, kVK_RightControl 0x3E; WinUser.h VK_LSHIFT 0xA0 .. VK_RMENU 0xA5. */
inline constexpr MacKeySidedVk kMacKeySidedVks[] = {
    {0x38, 0xA0}, {0x3A, 0xA4}, {0x3B, 0xA2}, {0x3C, 0xA1}, {0x3D, 0xA5}, {0x3E, 0xA3},
};

inline constexpr uint32_t kMacKeyCapsLock = 0x39;

inline constexpr uint8_t MacSidedVk(uint32_t code, uint8_t vk) {
    for (const MacKeySidedVk& s : kMacKeySidedVks)
        if (s.code == code) return s.vk;
    return vk;
}
