from __future__ import annotations

from pathlib import Path

import qt_windows
import vcpkg_install
from host_branch import WIN32_X86

LIBRARY_INCLUDES = ("libservicelocator/include", "libCerfEngine/include", "libCerfCore/include",
                    "cerf-qt", "cerf-qt/cerfman")
QT_MODULES = ("QtCore", "QtGui", "QtWidgets", "QtSvg", "QtNetwork", "QtQml", "QtQuick",
              "QtQuickControls2")

FIXED_FLAGS = ('"--target=i686-pc-windows-msvc"', '"/std:c++20"', '"/EHsc"', '"/permissive-"',
               '"-DWIN32"', '"-DNDEBUG"', '"-DUNICODE"', '"-D_UNICODE"', '"-DCERF_DEV_MODE=1"')


def generate(root: Path) -> Path:
    vcpkg_include = vcpkg_install.installed_prefix(root, vcpkg_install.TRIPLETS[WIN32_X86]) / "include"
    qt_include = qt_windows.prefix_dir(root) / "include"
    for missing in (p for p in (vcpkg_include, qt_include) if not p.is_dir()):
        print("[clangd] note: {} is not present yet; the first build creates it.".format(missing))
    lines = [
        "# AUTO-GENERATED by tools/gen_clangd.py -- do not edit; regenerated on every build.",
        "CompileFlags:",
        "  Compiler: clang-cl",
        "  Add:",
    ]
    lines += ["    - " + flag for flag in FIXED_FLAGS]
    includes = [vcpkg_include, qt_include] + [qt_include / module for module in QT_MODULES]
    includes += [root / inc for inc in LIBRARY_INCLUDES]
    lines += ['    - "-I{}"'.format(path.as_posix()) for path in includes]
    dest = root / ".clangd"
    dest.write_bytes("\n".join(lines).encode("utf-8"))
    print("[clangd] wrote {}".format(dest))
    return dest


if __name__ == "__main__":
    generate(Path(__file__).resolve().parent.parent)
